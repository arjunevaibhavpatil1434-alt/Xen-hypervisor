/*
 * ILI9341 SPI TFT for the FreeRTOS Xen guest: RK3288 SPI2 controller
 * (transmit only, polled, no IRQ, no DMA) plus two GPIO5 lines for DC and
 * RESET. See tft.h for the wiring.
 */
#include "FreeRTOS.h"
#include "task.h"
#include "tft.h"

#define SPI2_BASE       0xff130000UL
#define GPIO5_BASE      0xff7c0000UL
#define REG( b, o )     ( *( volatile uint32_t * ) ( ( b ) + ( o ) ) )

/* Rockchip SPI (drivers/spi/spi-rockchip.c) */
#define SPI_CTRLR0      0x000
#define SPI_SSIENR      0x008
#define SPI_SER         0x00c
#define SPI_BAUDR       0x010
#define SPI_TXFLR       0x01c
#define SPI_SR          0x024
#define SPI_IMR         0x02c
#define SPI_DMACR       0x03c
#define SPI_TXDR        0x400
#define SR_BUSY         ( 1UL << 0 )
#define SR_TFE          ( 1UL << 2 )
#define FIFO_DEPTH      32
/* 8-bit frames, mode 0, one-cycle CS setup, APB byte access, transmit only, master */
#define CTRLR0_TFT      ( ( 1UL << 0 ) | ( 1UL << 10 ) | ( 1UL << 13 ) | ( 1UL << 18 ) )
/*
 * SPI clock = sclk_spi2 (at most 50 MHz, rtos1-hwprep) / SPI_BAUD_DIV (even).
 * The ILI9341 write cycle is 100 ns minimum (10 MHz); /2 (24.75 MHz) is far
 * beyond that and, over header jumper wires, leaves the panel blank. /6 gives
 * 8.25 MHz from the usual 49.5 MHz.
 */
#ifndef SPI_BAUD_DIV
#define SPI_BAUD_DIV    6
#endif

/* Rockchip GPIO v1 */
#define GPIO_DR         0x00
#define GPIO_DDR        0x04
#define PIN_RST         ( 1UL << 11 )   /* GPIO5_B3, header pin 18 */
#define PIN_DC          ( 1UL << 19 )   /* GPIO5_C3, header pin 22 */

/* MADCTL: MV | BGR = landscape 320x240. 0xe8 (MY|MX|MV|BGR) turns it 180 degrees. */
#ifndef TFT_MADCTL
#define TFT_MADCTL      0x28
#endif

static void gpio_set( uint32_t pin, int high )
{
    __asm__ volatile ( "dsb" ::: "memory" );

    if( high )
    {
        REG( GPIO5_BASE, GPIO_DR ) |= pin;
    }
    else
    {
        REG( GPIO5_BASE, GPIO_DR ) &= ~pin;
    }

    __asm__ volatile ( "dsb" ::: "memory" );
}

static void spi_wait_idle( void )
{
    while( ( REG( SPI2_BASE, SPI_SR ) & ( SR_TFE | SR_BUSY ) ) != SR_TFE )
    {
    }
}

static inline void spi_byte( uint8_t b )
{
    while( REG( SPI2_BASE, SPI_TXFLR ) >= FIFO_DEPTH )
    {
    }

    REG( SPI2_BASE, SPI_TXDR ) = b;
}

static void tft_cmd( uint8_t c )
{
    spi_wait_idle();
    /* CS high then low again: the panel restarts its bit count on every
     * command, so a lost bit cannot shift everything after it */
    REG( SPI2_BASE, SPI_SER ) = 0;
    __asm__ volatile ( "dsb" ::: "memory" );
    REG( SPI2_BASE, SPI_SER ) = 1;
    gpio_set( PIN_DC, 0 );
    spi_byte( c );
    spi_wait_idle();
    gpio_set( PIN_DC, 1 );
}

static void tft_cmd_data( uint8_t c, const uint8_t * d, uint32_t n )
{
    tft_cmd( c );

    while( n-- )
    {
        spi_byte( *d++ );
    }
}

static void tft_window( uint32_t x, uint32_t y, uint32_t w, uint32_t h )
{
    uint32_t x1 = x + w - 1, y1 = y + h - 1;
    uint8_t ca[ 4 ] = { x >> 8, x, x1 >> 8, x1 };
    uint8_t pa[ 4 ] = { y >> 8, y, y1 >> 8, y1 };

    tft_cmd_data( 0x2a, ca, 4 );    /* CASET */
    tft_cmd_data( 0x2b, pa, 4 );    /* PASET */
    tft_cmd( 0x2c );                /* RAMWR: pixels follow */
}

static inline void tft_pixel( uint16_t c )
{
    spi_byte( c >> 8 );
    spi_byte( c & 0xff );
}

void tft_init( void )
{
    /* register count, then: command, number of data bytes, data... */
    static const uint8_t init[] =
    {
        0xef, 3, 0x03, 0x80, 0x02,
        0xcf, 3, 0x00, 0xc1, 0x30,          /* power control B */
        0xed, 4, 0x64, 0x03, 0x12, 0x81,    /* power on sequence */
        0xe8, 3, 0x85, 0x00, 0x78,          /* driver timing A */
        0xcb, 5, 0x39, 0x2c, 0x00, 0x34, 0x02, /* power control A */
        0xf7, 1, 0x20,                      /* pump ratio */
        0xea, 2, 0x00, 0x00,                /* driver timing B */
        0xc0, 1, 0x23,                      /* power control 1 */
        0xc1, 1, 0x10,                      /* power control 2 */
        0xc5, 2, 0x3e, 0x28,                /* VCOM 1 */
        0xc7, 1, 0x86,                      /* VCOM 2 */
        0x36, 1, TFT_MADCTL,                /* memory access: orientation, BGR */
        0x37, 1, 0x00,                      /* no vertical scroll */
        0x3a, 1, 0x55,                      /* 16 bits per pixel */
        0xb1, 2, 0x00, 0x18,                /* frame rate 79 Hz */
        0xb6, 3, 0x08, 0x82, 0x27,          /* display function */
        0xf2, 1, 0x00,                      /* 3-gamma off */
        0x26, 1, 0x01,                      /* gamma curve 1 */
        0xe0, 15, 0x0f, 0x31, 0x2b, 0x0c, 0x0e, 0x08, 0x4e, 0xf1,
                  0x37, 0x07, 0x10, 0x03, 0x0e, 0x09, 0x00,
        0xe1, 15, 0x00, 0x0e, 0x14, 0x03, 0x11, 0x07, 0x31, 0xc1,
                  0x48, 0x08, 0x0f, 0x0c, 0x31, 0x36, 0x0f,
    };
    uint32_t i;

    /* SPI2: master, transmit only, CS0 held low (the panel is alone on it) */
    REG( SPI2_BASE, SPI_SSIENR ) = 0;
    REG( SPI2_BASE, SPI_CTRLR0 ) = CTRLR0_TFT;
    REG( SPI2_BASE, SPI_BAUDR ) = SPI_BAUD_DIV;
    REG( SPI2_BASE, SPI_IMR ) = 0;
    REG( SPI2_BASE, SPI_DMACR ) = 0;
    REG( SPI2_BASE, SPI_SER ) = 1;
    REG( SPI2_BASE, SPI_SSIENR ) = 1;

    /* DC and RESET as outputs, then a hardware reset */
    gpio_set( PIN_DC | PIN_RST, 1 );
    REG( GPIO5_BASE, GPIO_DDR ) |= PIN_DC | PIN_RST;
    vTaskDelay( pdMS_TO_TICKS( 5 ) );
    gpio_set( PIN_RST, 0 );
    vTaskDelay( pdMS_TO_TICKS( 20 ) );
    gpio_set( PIN_RST, 1 );
    vTaskDelay( pdMS_TO_TICKS( 150 ) );

    tft_cmd( 0x01 );                        /* software reset */
    vTaskDelay( pdMS_TO_TICKS( 150 ) );

    for( i = 0; i < sizeof( init ); i += 2 + init[ i + 1 ] )
    {
        tft_cmd_data( init[ i ], &init[ i + 2 ], init[ i + 1 ] );
    }

    tft_cmd( 0x11 );                        /* sleep out */
    vTaskDelay( pdMS_TO_TICKS( 120 ) );
    tft_cmd( 0x29 );                        /* display on */
    spi_wait_idle();
}

void tft_fill( uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint16_t color )
{
    uint32_t n;

    if( ( w == 0 ) || ( h == 0 ) || ( x >= TFT_W ) || ( y >= TFT_H ) )
    {
        return;
    }

    if( x + w > TFT_W )
    {
        w = TFT_W - x;
    }

    if( y + h > TFT_H )
    {
        h = TFT_H - y;
    }

    tft_window( x, y, w, h );

    for( n = w * h; n > 0; n-- )
    {
        tft_pixel( color );
    }
}

