uint32_t tft_text( uint32_t x, uint32_t y, const char * s, uint32_t scale,
                   uint16_t fg, uint16_t bg )
{
    const uint32_t cw = 6 * scale, ch = 8 * scale;

    for( ; *s != '\0' && x + cw <= TFT_W && y + ch <= TFT_H; s++, x += cw )
    {
        const uint8_t * g = font5x7[ ( *s >= 0x20 && *s <= 0x7e ) ? *s - 0x20 : '?' - 0x20 ];
        uint32_t r, c;

        tft_window( x, y, cw, ch );

        for( r = 0; r < ch; r++ )
        {
            uint32_t fr = r / scale;

            for( c = 0; c < cw; c++ )
            {
                uint32_t fc = c / scale;
                int on = ( fc < 5 ) && ( fr < 7 ) && ( ( g[ fc ] >> fr ) & 1 );

                tft_pixel( on ? fg : bg );
            }
        }
    }

    return x;
}
